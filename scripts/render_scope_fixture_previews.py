"""Render four scope preview PNGs from deterministic fixture expectations.

Uses the same BT.709 formulas as the JS accumulate module so PR screenshots
match unit-tested math. Not a live media measurement.
"""
from __future__ import annotations

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "architecture" / "assets" / "scopes"

LUMA = (0.2126, 0.7152, 0.0722)
BARS = [
    (0.75, 0.75, 0.75),
    (0.75, 0.75, 0.0),
    (0.0, 0.75, 0.75),
    (0.0, 0.75, 0.0),
    (0.75, 0.0, 0.75),
    (0.75, 0.0, 0.0),
    (0.0, 0.0, 0.75),
]


def luma(r: float, g: float, b: float) -> float:
    return LUMA[0] * r + LUMA[1] * g + LUMA[2] * b


def cbcr(r: float, g: float, b: float) -> tuple[float, float]:
    y = luma(r, g, b)
    return (b - y) / 1.8556, (r - y) / 1.5748


def make_bars(width: int = 280, height: int = 160) -> list[tuple[float, float, float]]:
    pixels: list[tuple[float, float, float]] = []
    bar_w = width // len(BARS)
    for y in range(height):
        for x in range(width):
            bar = min(len(BARS) - 1, x // max(1, bar_w))
            pixels.append(BARS[bar])
    return pixels


def draw_histogram(path: Path) -> None:
    img = Image.new("RGB", (320, 180), (20, 20, 20))
    draw = ImageDraw.Draw(img)
    bins = [0] * 256
    for rgb in make_bars():
        for c in rgb:
            bins[min(255, int(256 * c))] += 1
    peak = max(bins) or 1
    pts = [
        (int(i / 255 * 319), 179 - int(bins[i] / peak * 170))
        for i in range(256)
        if bins[i]
    ]
    if len(pts) > 1:
        draw.line(pts, fill=(240, 240, 240), width=1)
    draw.text((8, 8), "Histogram (test pattern)", fill=(200, 200, 120))
    img.save(path)


def draw_waveform(path: Path) -> None:
    w, h = 320, 180
    img = Image.new("RGB", (w, h), (20, 20, 20))
    px = img.load()
    width, height = 280, 160
    for y in range(height):
        for x in range(width):
            bar = min(len(BARS) - 1, x // max(1, width // len(BARS)))
            yv = luma(*BARS[bar])
            dx = int(x / width * (w - 1))
            dy = h - 1 - int(yv * (h - 1))
            px[dx, dy] = (230, 230, 230)
    draw = ImageDraw.Draw(img)
    draw.text((8, 8), "Waveform Y' (test pattern)", fill=(200, 200, 120))
    img.save(path)


def draw_parade(path: Path) -> None:
    w, h = 320, 180
    img = Image.new("RGB", (w, h), (20, 20, 20))
    px = img.load()
    panel = w // 3
    colors = [(255, 70, 70), (70, 220, 110), (80, 130, 255)]
    width = 280
    for ch, color in enumerate(colors):
        for x in range(width):
            bar = min(len(BARS) - 1, x // max(1, width // len(BARS)))
            value = BARS[bar][ch]
            dx = ch * panel + int((x / width) * (panel - 1))
            dy = h - 1 - int(value * (h - 1))
            px[dx, dy] = color
    draw = ImageDraw.Draw(img)
    draw.text((8, 8), "RGB Parade (test pattern)", fill=(200, 200, 120))
    img.save(path)


def draw_vectorscope(path: Path) -> None:
    size = 180
    img = Image.new("RGB", (size, size), (20, 20, 20))
    px = img.load()
    cx = cy = size // 2
    for rgb in BARS:
        cb, cr = cbcr(*rgb)
        x = int((cb + 0.5) * (size - 1))
        y = int((0.5 - cr) * (size - 1))
        for oy in range(-1, 2):
            for ox in range(-1, 2):
                xx, yy = x + ox, y + oy
                if 0 <= xx < size and 0 <= yy < size:
                    px[xx, yy] = (120, 220, 180)
    draw = ImageDraw.Draw(img)
    draw.line((cx, 0, cx, size - 1), fill=(80, 80, 80))
    draw.line((0, cy, size - 1, cy), fill=(80, 80, 80))
    draw.text((6, 6), "Vectorscope Cb/Cr", fill=(200, 200, 120))
    draw.text((size - 40, cy - 14), "Cb", fill=(160, 160, 160))
    draw.text((cx + 4, 4), "Cr", fill=(160, 160, 160))
    img.save(path)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    draw_histogram(OUT / "histogram-color-bars.png")
    draw_waveform(OUT / "waveform-color-bars.png")
    draw_parade(OUT / "parade-color-bars.png")
    draw_vectorscope(OUT / "vectorscope-color-bars.png")
    (OUT / "README.md").write_text(
        "# Scope fixture previews\n\n"
        "Test-pattern visualizations for PR #362. Not live media analysis.\n"
        "Generated by `scripts/render_scope_fixture_previews.py`.\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
